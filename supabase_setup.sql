-- HANI 4 BODY Supabase setup
create table if not exists public.hani4body_results (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  age_group text not null,
  sex text not null,
  qi int not null check (qi between 0 and 100),
  blood int not null check (blood between 0 and 100),
  yin int not null check (yin between 0 and 100),
  yang int not null check (yang between 0 and 100)
);

alter table public.hani4body_results enable row level security;

drop policy if exists "anon can insert hani4body results" on public.hani4body_results;
create policy "anon can insert hani4body results"
on public.hani4body_results for insert to anon
with check (true);

-- Raw rows are NOT exposed to anonymous users.
revoke all on public.hani4body_results from anon;
grant insert on public.hani4body_results to anon;
grant usage, select on sequence public.hani4body_results_id_seq to anon;

create or replace function public.hani4body_peer_stats(
  p_age_group text, p_sex text,
  p_qi int, p_blood int, p_yin int, p_yang int
)
returns table(
  n bigint,
  avg_qi numeric, avg_blood numeric, avg_yin numeric, avg_yang numeric,
  pct_qi numeric, pct_blood numeric, pct_yin numeric, pct_yang numeric
)
language sql
security definer
set search_path = public
stable
as $$
  select
    count(*)::bigint,
    round(avg(qi)::numeric,1), round(avg(blood)::numeric,1),
    round(avg(yin)::numeric,1), round(avg(yang)::numeric,1),
    round((100.0*count(*) filter(where qi <= p_qi)/nullif(count(*),0))::numeric,1),
    round((100.0*count(*) filter(where blood <= p_blood)/nullif(count(*),0))::numeric,1),
    round((100.0*count(*) filter(where yin <= p_yin)/nullif(count(*),0))::numeric,1),
    round((100.0*count(*) filter(where yang <= p_yang)/nullif(count(*),0))::numeric,1)
  from public.hani4body_results
  where age_group=p_age_group and sex=p_sex;
$$;

revoke all on function public.hani4body_peer_stats(text,text,int,int,int,int) from public;
grant execute on function public.hani4body_peer_stats(text,text,int,int,int,int) to anon;
